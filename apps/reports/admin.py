# apps/reports/admin.py

from django.contrib    import admin
from django.utils.html import format_html
from django.utils      import timezone
from .models           import ReportRequest, ScheduledReport


# ─────────────────────────────────────────────
#  Report Request Admin
# ─────────────────────────────────────────────

@admin.register(ReportRequest)
class ReportRequestAdmin(admin.ModelAdmin):
    list_display   = [
        'title', 'report_type_display', 'format',
        'status_display', 'requested_by',
        'requested_at', 'duration_display',
    ]
    list_filter    = ['report_type', 'format', 'status', 'requested_at']
    search_fields  = ['title', 'requested_by__first_name']
    readonly_fields= [
        'report_type', 'format', 'title', 'parameters',
        'status', 'file', 'error_message',
        'requested_by', 'requested_at', 'completed_at',
    ]
    date_hierarchy = 'requested_at'
    ordering       = ['-requested_at']
    actions        = ['mark_failed', 'delete_selected']

    def report_type_display(self, obj):
        return obj.get_report_type_display()
    report_type_display.short_description = 'Report Type'

    def status_display(self, obj):
        colours = {
            'ready':      ('green',   '✔ Ready'),
            'pending':    ('#f59e0b', '◷ Pending'),
            'processing': ('#1a3c72', '⟳ Processing'),
            'failed':     ('red',     '✕ Failed'),
        }
        colour, label = colours.get(obj.status, ('#9ca3af', obj.status))
        return format_html(
            '<span style="color:{};font-weight:700">{}</span>',
            colour, label
        )
    status_display.short_description = 'Status'

    def duration_display(self, obj):
        secs = obj.duration_seconds
        if secs is None:
            return '—'
        if secs < 60:
            return f'{secs}s'
        return f'{secs // 60}m {secs % 60}s'
    duration_display.short_description = 'Duration'

    def mark_failed(self, request, queryset):
        queryset.update(
            status='failed',
            error_message='Manually marked failed by admin',
            completed_at=timezone.now(),
        )
        self.message_user(request, f'{queryset.count()} report(s) marked failed.')
    mark_failed.short_description = 'Mark selected as failed'

    def has_add_permission(self, request):
        return False  # Reports are generated by views, not created manually


# ─────────────────────────────────────────────
#  Scheduled Report Admin
# ─────────────────────────────────────────────

@admin.register(ScheduledReport)
class ScheduledReportAdmin(admin.ModelAdmin):
    list_display   = [
        'title', 'report_type_display', 'frequency',
        'is_active', 'last_run', 'next_run',
        'recipient_count', 'created_by',
    ]
    list_filter    = ['frequency', 'is_active', 'report_type']
    search_fields  = ['title']
    readonly_fields= ['last_run', 'next_run', 'created_at']
    filter_horizontal = ['recipients']
    actions        = ['activate', 'deactivate']

    def report_type_display(self, obj):
        return obj.get_report_type_display()
    report_type_display.short_description = 'Report Type'

    def recipient_count(self, obj):
        count = obj.recipients.count()
        return format_html(
            '<span style="color:#1a3c72;font-weight:700">{}</span> user{}',
            count, 's' if count != 1 else ''
        )
    recipient_count.short_description = 'Recipients'

    def activate(self, request, queryset):
        queryset.update(is_active=True)
        self.message_user(request, f'{queryset.count()} schedule(s) activated.')
    activate.short_description = 'Activate selected'

    def deactivate(self, request, queryset):
        queryset.update(is_active=False)
        self.message_user(request, f'{queryset.count()} schedule(s) deactivated.')
    deactivate.short_description = 'Deactivate selected'

    def save_model(self, request, obj, form, change):
        if not change:
            obj.created_by = request.user
        super().save_model(request, obj, form, change)